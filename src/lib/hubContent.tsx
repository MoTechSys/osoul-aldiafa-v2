export function getHubContent(slug: string): {
  page: LocalServicePageProps;
  faqs: FAQ[];
} {
  const hub = SERVICE_HUBS[slug];
  const d = HUB_DATA[slug];
  if (!hub || !d) throw new Error(`Unknown hub: ${slug}`);

  return {
    faqs: d.faqs,
    page: {
      h1: hub.h1,
      cityAr: "السعودية",
      serviceAr: hub.ar,
      intro: d.intro,
      heroImage: d.hero,
      heroAlt: d.heroAlt,
      ...("blocks" in d ? {
        blocks: d.blocks.map((block) => block.type === "faq" ? { ...block, faqs: d.faqs } : block),
      } : {
        sections: d.sections,
        extraSections: d.extraSections,
        districts: Object.values(CITIES).map((c) => c.ar),
        packages: d.packages,
        pricingNote: "* يُناقش نطاق الخدمة بعد معرفة تفاصيل مناسبتك، وتُثبت العناصر المتفق عليها في عرض مكتوب.",
        whyUs: d.whyUs,
        gallery: d.gallery,
        otherCities: CITY_LINKS,
      }),
      faqs: d.faqs,
      breadcrumbItems: [
        { label: "الرئيسية", href: "/" },
        { label: "خدماتنا", href: "/services" },
        { label: hub.ar, href: `/${hub.slug}` },
      ],
    },
  };
}
