/**
 * المسارات «المستقلة» — صفحات تُعرض بلا هيكل الموقع.
 *
 * لماذا يوجد هذا الملف؟
 * صفحة `/links` هي صفحة «رابط في البايو» (link-in-bio): يفتحها الزائر من
 * انستقرام أو تيك توك ليختار قناة تواصل واحدة ثم يخرج. قياسٌ بالمتصفح أثبت
 * أن هيكل الموقع كان يفسدها فعليًا:
 *   • الشريط السفلي العائم (BottomNav) كان يغطّي بطاقة X جسديًا.
 *   • الفوتر الكامل كان يُلحق أسفلها بأزرار التواصل القديمة الثلاثة —
 *     أي قائمتان متناقضتان للتواصل في الشاشة نفسها.
 *   • الشريط العلوي (Navbar) كان يتراكب مع شعار الصفحة.
 *
 * الحل مركزيّ لا مبعثر: أي مكوّن هيكلي يسأل `isStandaloneRoute()` قبل أن
 * يرسم نفسه، فلا يمكن أن يُنسى مكوّن واحد ويعود العيب من الخلف.
 *
 * ملاحظة عن المطابقة: نستخدم مطابقة تامة + بادئة مع «/» بعدها، حتى لا
 * يُطابق مسار مثل `/links-something` عن طريق الخطأ.
 */
export const STANDALONE_ROUTES: readonly string[] = ["/links"];

export function isStandaloneRoute(pathname: string | null | undefined): boolean {
  if (!pathname) return false;
  return STANDALONE_ROUTES.some(
    (route) => pathname === route || pathname.startsWith(`${route}/`)
  );
}
